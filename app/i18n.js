  // Idioma admitido más parecido a uno pedido ("pt-BR" -> "pt"), o el de reserva.
  function resolve(lang) {
    const base = String(lang || '').toLowerCase().split(/[-_]/)[0];
    return Object.prototype.hasOwnProperty.call(LANGUAGES, base) ? base : FALLBACK;
  }

  // Busca la clave en el idioma pedido y, si falta, en inglés. Con fallback === null devuelve null si no existe.
  function t(lang, key, vars, fallback) {
    const table = STRINGS[resolve(lang)] || {};
    let s = table[key];
    if (s === undefined) s = STRINGS[FALLBACK][key];
    if (s === undefined) return fallback === undefined ? key : fallback;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  // Traduce los elementos marcados con data-i18n (texto), data-i18n-title, data-i18n-aria y data-i18n-placeholder.
  function apply(lang, root) {
    for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = t(lang, e.dataset.i18n);
    for (const e of root.querySelectorAll('[data-i18n-title]')) e.title = t(lang, e.dataset.i18nTitle);
    for (const e of root.querySelectorAll('[data-i18n-aria]')) e.setAttribute('aria-label', t(lang, e.dataset.i18nAria));
    for (const e of root.querySelectorAll('[data-i18n-placeholder]')) e.placeholder = t(lang, e.dataset.i18nPlaceholder);
  }

  // Duración en horas y minutos ("3 h 7 min"), o solo minutos si no llega a una hora.
  function duration(lang, seconds) {
    const total = Math.floor((seconds || 0) / 60), h = Math.floor(total / 60), m = total % 60;
    return h ? t(lang, 'time.hm', { h, m }) : t(lang, 'time.m', { m });
  }

  return { LANGUAGES, FALLBACK, STRINGS, resolve, t, apply, duration };
